#!/usr/bin/env python3
"""Generate the reviewer overlays for the Codex-native skills.

Both overlays are rebuilt from ``skills/skills-codex`` (itself generated by
``tools/sync_codex_skill_mirror.py``), swapping the secondary Codex agent for an
external reviewer reached through a local MCP bridge:

- ``skills/skills-codex-claude-review`` — Claude via ``claude-review``
- ``skills/skills-codex-gemini-review`` — Gemini via ``gemini-review``

Run after the mirror sync: ``python3 tools/generate_codex_claude_review_overrides.py``
(``--reviewer claude`` or ``--reviewer gemini`` to rebuild just one).
"""

from __future__ import annotations

import argparse
import ast
import re
import shutil
from dataclasses import dataclass
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
SRC_ROOT = REPO_ROOT / "skills" / "skills-codex"

FRONTMATTER_RE = re.compile(r"^---\n(.*?)\n---\n?", re.DOTALL)
SPAWN_BLOCK_RE = re.compile(r"```(?:yaml|text)?\nspawn_agent:\n([\s\S]*?)```")
SEND_BLOCK_RE = re.compile(r"```(?:yaml|text)?\nsend_input:\n([\s\S]*?)```")

CLAUDE_SKILLS = [
    "research-review",
    "novelty-check",
    "research-refine",
    "auto-review-loop",
    "paper-plan",
    "paper-figure",
    "paper-write",
    "auto-paper-improvement-loop",
]
GEMINI_SKILLS = CLAUDE_SKILLS + [
    "idea-creator",
    "idea-discovery",
    "grant-proposal",
    "paper-writing",
    "paper-slides",
    "paper-poster-html",
]


@dataclass(frozen=True)
class Reviewer:
    key: str            # claude | gemini
    name: str           # display name of the reviewer model family
    override_who: str   # who the override note says acts as the reviewer
    bridge: str         # MCP server / bridge name
    tool_prefix: str    # MCP tool prefix as Codex exposes it
    model_env: str      # env var for a specific model override
    skills: tuple[str, ...]

    @property
    def dest(self) -> Path:
        return REPO_ROOT / "skills" / f"skills-codex-{self.bridge}"

    @property
    def start(self) -> str:
        return f"{self.tool_prefix}review_start"

    @property
    def reply(self) -> str:
        return f"{self.tool_prefix}review_reply_start"

    @property
    def status(self) -> str:
        return f"{self.tool_prefix}review_status"


REVIEWERS = {
    "claude": Reviewer("claude", "Claude", "**Claude Code**", "claude-review",
                       "mcp__claude_review__", "CLAUDE_REVIEW_MODEL", tuple(CLAUDE_SKILLS)),
    "gemini": Reviewer("gemini", "Gemini", "**Gemini**", "gemini-review",
                       "mcp__gemini-review__", "GEMINI_REVIEW_MODEL", tuple(GEMINI_SKILLS)),
}


def override_note(r: Reviewer) -> str:
    return (
        f"> Override for Codex users who want {r.override_who}, not a second Codex agent, "
        f"to act as the reviewer. Install this package **after** `skills/skills-codex/*`."
    )


def reviewer_line(r: Reviewer) -> str:
    return (
        f"- **REVIEWER_MODEL = `{r.bridge}`** — {r.name} reviewer invoked through the "
        f"local `{r.bridge}` MCP bridge. Set `{r.model_env}` if you need a "
        f"specific {r.name} model override."
    )


def prereq_block(r: Reviewer) -> str:
    return f"""## Prerequisites

- Install the base Codex-native skills first: copy `skills/skills-codex/*` into `~/.codex/skills/`.
- Then install this overlay package: copy `skills/skills-codex-{r.bridge}/*` into `~/.codex/skills/` and allow it to overwrite the same skill names.
- Register the local reviewer bridge:
  ```bash
  codex mcp add {r.bridge} -- python3 ~/.codex/mcp-servers/{r.bridge}/server.py
  ```
- This gives Codex access to `{r.start}`, `{r.reply}`, and `{r.status}`.
""".strip()


def extract_field(frontmatter: str, field: str) -> str:
    pattern = re.compile(rf"^{re.escape(field)}:\s*(.+)$", re.MULTILINE)
    match = pattern.search(frontmatter)
    if not match:
        return ""
    value = match.group(1).strip()
    if (value.startswith('"') and value.endswith('"')) or (value.startswith("'") and value.endswith("'")):
        try:
            value = ast.literal_eval(value)
        except (SyntaxError, ValueError):
            value = value[1:-1]
    return value


def build_frontmatter(name: str, description: str) -> str:
    safe_desc = description.replace('"', '\\"')
    return f'---\nname: "{name}"\ndescription: "{safe_desc}"\n---\n\n'


def normalize_description(text: str, r: Reviewer) -> str:
    text = text or f"{r.name}-review override for a Codex-native ARIS skill."
    via = f"{r.name} via {r.bridge} MCP"
    text = text.replace("GPT using a secondary Codex agent", via)
    text = text.replace("using a secondary Codex agent", f"using {via}")
    for model in ("GPT-6-Astra", "GPT-5.5"):
        text = text.replace(f"via {model} xhigh review", f"via {r.name} review through {r.bridge} MCP")
        text = text.replace(f"via iterative {model} review", f"via iterative {r.name} review through {r.bridge} MCP")
    return text


def _rewrite_block(match: re.Match[str], tool: str, renames: dict[str, str]) -> str:
    out = ["```", f"{tool}:"]
    for line in match.group(1).splitlines():
        stripped = line.strip()
        if stripped.startswith("model:") or stripped.startswith("reasoning_effort:"):
            continue
        for old, new in renames.items():
            if stripped.startswith(old):
                line = line.replace(old, new, 1)
                break
        out.append(line)
    out.append("```")
    return "\n".join(out)


def append_async_notes(text: str, r: Reviewer) -> str:
    note = (
        "After this start call, immediately save the returned `jobId` and poll "
        f"`{r.status}` with a bounded `waitSeconds` until "
        "`done=true`. Treat the completed status payload's `response` as the "
        "reviewer output, and save the completed `threadId` for any follow-up round."
    )

    def repl(match: re.Match[str]) -> str:
        block = match.group(0)
        return block if note in block else f"{block}\n\n{note}"

    starts = f"(?:{re.escape(r.start)}:|{re.escape(r.reply)}:)"
    return re.sub(rf"```(?:yaml|text)?\n{starts}[\s\S]*?```", repl, text)


def transform_body(text: str, r: Reviewer) -> str:
    who = f"{r.name} reviewer via `{r.bridge}` MCP"
    poll = f"then poll `{r.status}` with the returned `jobId` until `done=true`"
    strict = f"Always ask the {r.name} reviewer for strict, high-rigor feedback"
    text = text.replace("secondary Codex agent", who)
    text = text.replace(f"via a {who} (xhigh reasoning)", f"via `{r.bridge}` MCP (high-rigor review)")
    text = text.replace("secondary Codex agent (xhigh reasoning)", who)
    # Longer phrases first: the bare "<model> xhigh" rule would otherwise consume them.
    for model in ("GPT-6-Astra", "GPT-5.5"):
        text = text.replace(f"Send the full paper text to {model} xhigh:", f"Send the full paper text to {r.name} through `{r.bridge}`:")
        text = text.replace(f"Send the complete outline to {model} xhigh for feedback:", f"Send the complete outline to {r.name} for feedback:")
        text = text.replace(f"{model} xhigh", f"{r.name} review")
        text = text.replace(f"{model} responses", f"{r.name} reviewer responses")
    text = text.replace("Call REVIEWER_MODEL via `spawn_agent` (`spawn_agent`) with xhigh reasoning:", f"Call REVIEWER_MODEL via `{r.start}` with high-rigor review:")
    text = text.replace("Send a detailed prompt with xhigh reasoning:", "Send a detailed prompt with high-rigor review:")
    text = text.replace("Use `send_input` with the returned agent id to continue the conversation:", f"Use `{r.reply}` with the saved completed `threadId`, {poll} to continue the conversation:")
    text = text.replace("If this is round 2+, use `send_input` with the saved agent id to maintain continuity.", f"If this is round 2+, use `{r.reply}` with the saved completed `threadId`, {poll} to maintain continuity.")
    text = text.replace("Save the agent id for Round 2.", f"Save the returned `jobId`, poll `{r.status}` until `done=true`, then save the completed `threadId` for Round 2.")
    text = text.replace("Save agent id from first call, use `send_input` for subsequent rounds", f"Save the completed `threadId` from the first `{r.status}` result, then use `{r.reply}` plus `{r.status}` for subsequent rounds")
    text = text.replace("Document the agent id for potential future resumption", "Document the completed `threadId` for potential future resumption")
    text = text.replace("Use `send_input` with the saved agent id:", f"Use `{r.reply}` with the saved completed `threadId`:")
    text = text.replace("use `send_input` for Round 2 to maintain conversation context", f"use `{r.reply}` plus `{r.status}` for Round 2 to maintain conversation context")
    text = text.replace("**CRITICAL: Save the `agent_id`** from this call for all later rounds.", f"**CRITICAL: Save the returned `jobId`**, poll `{r.status}` until `done=true`, then save the completed `threadId` from the status result for all later rounds.")
    text = text.replace("- **ALWAYS use `reasoning_effort: xhigh`** for all Codex review calls.", f"- **{strict}** in every review round.")
    text = text.replace("- **Save `agent_id` from Phase 2** and use `send_input` for later rounds.", f"- **Save the completed `threadId` from Phase 2** and use `{r.reply}` plus `{r.status}` for later rounds.")
    text = text.replace("- **Use `send_input`** for Round 2 to maintain conversation context", f"- **Use `{r.reply}` plus `{r.status}`** for Round 2 to maintain conversation context")
    text = text.replace("`agent_id`", "`thread_id`")
    text = text.replace('"agent_id"', '"thread_id"')
    text = text.replace("ALWAYS use `reasoning_effort: xhigh` for reviews", f"{strict}.")
    text = text.replace("ALWAYS use `reasoning_effort: xhigh` for maximum reasoning depth", f"{strict}.")
    text = re.sub(r"^-\s+\*{0,2}REVIEWER_MODEL.*$", lambda _m: reviewer_line(r), text, flags=re.MULTILINE)
    # The whole section, up to the next H2 — mainline bullets carry indented code blocks.
    text = re.sub(r"^## Prerequisites\n[\s\S]*?(?=^## |\Z)", lambda _m: prereq_block(r) + "\n\n",
                  text, count=1, flags=re.MULTILINE)
    text = SPAWN_BLOCK_RE.sub(lambda m: _rewrite_block(m, r.start, {"message:": "prompt:"}), text)
    text = SEND_BLOCK_RE.sub(lambda m: _rewrite_block(m, r.reply, {"id:": "threadId:", "message:": "prompt:"}), text)
    text = text.replace(
        "```\nreasoning_effort: xhigh\n```",
        f"```\n{r.start}:\n  prompt: |\n    [Full novelty briefing + prior work list + specific novelty questions]\n```",
    )
    # Final pass: the mainline-generated mirror also names the Codex tools in
    # backend-branch prose, tracing rules and fallback notes. In an overlay every
    # reviewer call belongs to this reviewer, so no Codex subagent call survives.
    text = text.replace("(no OpenAI API key)", f"(the `{r.bridge}` MCP bridge is not registered)")
    text = text.replace("(reuse agent_id)", "(reuse the completed `threadId`)")
    text = text.replace("saved agent_id", "saved completed `threadId`")
    for old, new in (("spawn_agent", r.start), ("send_input", r.reply)):
        text = text.replace(f"`{old}`", f"`{new}`").replace(f"{old}:", f"{new}:")
    return append_async_notes(text, r)


def generate_one(skill_name: str, r: Reviewer) -> None:
    skill_path = SRC_ROOT / skill_name / "SKILL.md"
    content = skill_path.read_text(encoding="utf-8")
    match = FRONTMATTER_RE.match(content)
    if not match:
        raise ValueError(f"Missing frontmatter: {skill_path}")

    frontmatter = match.group(1)
    body = content[match.end():].lstrip("\n")
    name = extract_field(frontmatter, "name") or skill_name
    description = normalize_description(extract_field(frontmatter, "description"), r)

    output = build_frontmatter(name, description)
    output += override_note(r) + "\n\n"
    output += transform_body(body, r).rstrip() + "\n"

    target_dir = r.dest / skill_name
    if target_dir.exists():
        shutil.rmtree(target_dir)
    target_dir.mkdir(parents=True, exist_ok=True)
    (target_dir / "SKILL.md").write_text(output, encoding="utf-8")


def generate(r: Reviewer) -> None:
    r.dest.mkdir(parents=True, exist_ok=True)
    # Drop overlay skills that left the target list (e.g. paper-poster → paper-poster-html);
    # README files and anything without a SKILL.md are left alone.
    for path in sorted(r.dest.iterdir()):
        if path.is_dir() and (path / "SKILL.md").is_file() and path.name not in r.skills:
            shutil.rmtree(path)
    for skill_name in r.skills:
        generate_one(skill_name, r)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--reviewer", choices=sorted(REVIEWERS), action="append",
                        help="rebuild only this overlay (repeatable); default: all")
    args = parser.parse_args()
    for key in args.reviewer or sorted(REVIEWERS):
        generate(REVIEWERS[key])


if __name__ == "__main__":
    main()
